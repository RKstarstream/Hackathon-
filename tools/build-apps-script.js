'use strict';
// Builds the Google Apps Script web app pages in apps-script/ from the website sources in public/.
//   node tools/build-apps-script.js            write apps-script/Index.html, Account.html, Portal.html, Admin.html, Seed.gs
//   node tools/build-apps-script.js --out DIR  write them somewhere else (used by the tests)
// Code.gs and appsscript.json in apps-script/ are hand-written and are not touched.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const dataUri = (file, type) => `data:${type};base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`;
const outArg = process.argv.indexOf('--out');
const out = outArg > 0 ? path.resolve(process.argv[outArg + 1]) : path.join(root, 'apps-script');

// Every edit must apply exactly as expected, so a change in public/ cannot silently break the Apps Script build.
function edit(text, from, to, { file, count = 1 } = {}) {
  const found = text.split(from).length - 1;
  if (count === 'any' ? found < 1 : found !== count) throw new Error(`${file}: expected ${count} occurrence(s) of ${JSON.stringify(from)}, found ${found}`);
  return text.split(from).join(typeof to === 'function' ? to() : to);
}
// Inline code must not end its own <script> or <style> element early.
function inlineSafe(code, file, tag) {
  if (new RegExp(`</${tag}`, 'i').test(code)) throw new Error(`${file} contains </${tag}> and cannot be inlined`);
  return code;
}

const bridge = inlineSafe(read('tools/apps-script-bridge.js'), 'apps-script-bridge.js', 'script');
const head = `<script>window.TT_CONFIG = __TT_CONFIG__;</script>\n<script>\n${bridge}</script>`;
const banner = (sources) => `<!-- Generated by tools/build-apps-script.js from ${sources}. Edit those files and rebuild instead of editing this file. -->`;
function withHead(html, file, sources) {
  if (!/^<!doctype html>/i.test(html)) throw new Error(`${file} must start with <!doctype html>`);
  html = html.replace(/^<!doctype html>\s*/i, `<!doctype html>\n${banner(sources)}\n`);
  return edit(html, '<meta charset="utf-8">', (m) => `<meta charset="utf-8">\n${head}\n`, { file });
}
const style = (file) => `<style>\n${inlineSafe(read(file), file, 'style')}\n</style>`;
const script = (code, file) => `<script>\n${inlineSafe(code, file, 'script')}\n</script>`;
// Apps Script calls take longer than local requests, especially when the script starts cold.
const longerTimeouts = (code, file) => code.replace(/AbortSignal\.timeout\((\d+)\)/g, (m, ms) => `AbortSignal.timeout(${Math.max(Number(ms), 25000) * (Number(ms) >= 20000 ? 2 : 1)})`);

const THREE_SRI = 'sha512-dLxUelApnYxpLt6K2iomGngnHO83iUvZytA3YjDUCjT0HDOHKXnVYdf3hU4JjM8uEhxf9nD1/ey98U3t2vZ0qQ==';
const threeTag = `<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js" integrity="${THREE_SRI}" crossorigin="anonymous" referrerpolicy="no-referrer"></script>
<script>window.THREE || document.write('<script src="https://cdn.jsdelivr.net/npm/three@0.128.0/build/three.min.js" integrity="${THREE_SRI}" crossorigin="anonymous"><\\/script>');</script>`;

function buildIndex() {
  const file = 'public/index.html';
  let html = withHead(read(file), file, 'public/index.html, world.css, world.js and vendor/three-post.js');
  html = edit(html, '<link rel="stylesheet" href="world.css">', () => style('public/world.css'), { file });
  html = edit(html, '<script src="vendor/three.min.js"></script>', () => threeTag, { file });
  // Three.js is the same r128 file as public/vendor/three.min.js (checked by the integrity hash). The post-processing
  // add-ons need it, and the site falls back to its flat layout if it cannot load.
  html = edit(html, '<script src="vendor/three-post.js"></script>', () => script(`if (window.THREE) {\n${read('public/vendor/three-post.js')}\n}`, 'three-post.js'), { file });
  let js = read('public/world.js');
  js = edit(js, "codeCheck.src = '/icons/check.svg'", () => `codeCheck.src = '${dataUri('public/icons/check.svg', 'image/svg+xml')}'`, { file: 'public/world.js' });
  js = longerTimeouts(js, 'public/world.js');
  html = edit(html, '<script src="world.js"></script>', () => script(js, 'public/world.js'), { file });
  return html;
}

function buildAccount() {
  const file = 'public/account.html';
  let html = withHead(read(file), file, 'public/account.html, portal.css, account.js and payment-qr.png');
  html = edit(html, '<link rel="stylesheet" href="/portal.css">', () => style('public/portal.css'), { file });
  const qr = dataUri('public/payment-qr.png', 'image/png');
  html = edit(html, 'src="/payment-qr.png"', () => `src="${qr}"`, { file });
  // Embed the QR image once; the download link reuses it.
  html = edit(html, 'href="/payment-qr.png"', 'href="#" data-qr-download', { file });
  let js = "document.querySelectorAll('[data-qr-download]').forEach((a) => { const img = document.querySelector('.payment-qr'); if (img) a.href = img.src; });\n" + read('public/account.js');
  js = edit(js, "location.pathname === '/register'", 'TT.page === \'register\'', { file: 'public/account.js' });
  js = edit(js, "location.assign('/portal')", "TT.navigate('/portal', { title: 'Welcome to Tech Tank', text: 'You are signed in. Your participant portal is ready.' })", { file: 'public/account.js' });
  js = longerTimeouts(js, 'public/account.js');
  html = edit(html, '<script src="/account.js"></script>', () => script(js, 'public/account.js'), { file });
  return html;
}

function buildPortal() {
  const file = 'public/portal.html';
  let html = withHead(read(file), file, 'public/portal.html, portal.css and portal.js');
  html = edit(html, '<link rel="stylesheet" href="/portal.css">', () => style('public/portal.css'), { file });
  let js = read('public/portal.js');
  js = edit(js, "location.replace('/login')", "TT.navigate('/login')", { file: 'public/portal.js', count: 2 });
  js = longerTimeouts(js, 'public/portal.js');
  html = edit(html, '<script src="/portal.js"></script>', () => script(js, 'public/portal.js'), { file });
  return html;
}

function buildAdmin() {
  const file = 'public/admin.html';
  let html = withHead(read(file), file, 'public/admin.html and admin.js');
  let js = read('public/admin.js');
  js = edit(js, 'new XMLHttpRequest()', 'new TT.UploadRequest()', { file: 'public/admin.js' });
  js = edit(js, "'Images and videos up to 60 MB each.'", "'Images and videos up to 20 MB each, stored in your Google Drive data folder. Add larger videos with a YouTube or Drive link.'", { file: 'public/admin.js' });
  js = edit(js, 'Participants create an account at /register and sign in at /login.', 'Participants create an account on the Register page and sign in on the Sign in page.', { file: 'public/admin.js' });
  js = edit(js, 'after creating an account at /register.', 'after creating an account on the Register page.', { file: 'public/admin.js' });
  html = edit(html, '<script src="/admin.js"></script>', () => script(js, 'public/admin.js'), { file });
  return html;
}

function buildSeed() {
  // The sample gallery images are embedded so the first deployment looks complete without extra uploads.
  const content = JSON.parse(read('data/content.json'));
  for (const item of content.media || []) {
    const m = /^\/uploads\/([\w.-]+\.svg)$/.exec(item.url || '');
    if (!m || !fs.existsSync(path.join(root, 'public/uploads', m[1]))) continue;
    // The server infers a sample card's topic from its file name; keep it once the name is gone.
    if (!item.topic) item.topic = /sample-crisis-card/i.test(m[1]) ? 'twist' : /sample-theme/i.test(m[1]) ? 'theme' : /sample-campaign/i.test(m[1]) ? 'campaign' : 'media';
    item.url = dataUri(path.join('public/uploads', m[1]), 'image/svg+xml');
  }
  return `/**
 * Generated by tools/build-apps-script.js from data/content.json.
 * The event content used the first time setup() runs. After that, edit content in the Control Room.
 */
var SEED_CONTENT_ = ${JSON.stringify(content, null, 2)};
`;
}

// Apps Script pages run inside a frame on another domain: nothing may load from the website's own paths.
function checkNoLocalAssets(html, name) {
  const local = [...html.matchAll(/\b(?:src|href)="(\/[^"]*)"/g)].map((m) => m[1]).filter((p) => !/^\/(?:login|register|portal|admin)?(?:#[\w-]*)?$/.test(p));
  if (local.length) throw new Error(`${name} still references local files: ${[...new Set(local)].join(', ')}`);
  if (!html.includes('__TT_CONFIG__')) throw new Error(`${name} is missing the configuration placeholder`);
}

const pages = { 'Index.html': buildIndex(), 'Account.html': buildAccount(), 'Portal.html': buildPortal(), 'Admin.html': buildAdmin() };
fs.mkdirSync(out, { recursive: true });
for (const [name, html] of Object.entries(pages)) {
  checkNoLocalAssets(html, name);
  fs.writeFileSync(path.join(out, name), html);
}
fs.writeFileSync(path.join(out, 'Seed.gs'), buildSeed());
if (outArg < 0) console.log('Apps Script web app built in apps-script/. Push it with clasp, or copy the files into the Apps Script editor.');
